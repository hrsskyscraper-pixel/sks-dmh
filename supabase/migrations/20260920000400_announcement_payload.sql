-- お知らせの構造化データ（デイリーレポートの名前リンク用）
-- =============================================
-- 2026-09-20 決定: 昨日のMBレポートの「スキルを習得した方」「認定いただいた方」「メッセージを贈った方」を
-- 名前リンクにして、タップするとタイムラインがその人・その日の分に絞り込まれるようにする。
-- 本文（body）は従来どおり残し、payload に人ごとの id・件数を持つ。古いレポート（payload なし）は本文のまま表示。
ALTER TABLE public.announcements ADD COLUMN IF NOT EXISTS payload JSONB;
COMMENT ON COLUMN public.announcements.payload IS 'デイリーレポート等の構造化データ（表示のリンク化に使う）。NULL＝本文のみ';
